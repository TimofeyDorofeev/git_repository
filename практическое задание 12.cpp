#include <iostream>   
using namespace std;

char maze[100][100];  // сам лабиринт из символов (не больше 100 x 100)
int dp[100][100];     // максимум pdf можно собрать до клетки (i, j)

int main() {
    int n, m;                         // размеры лабиринта
    cout << "Введите N и M: ";
    cin >> n >> m;

    cout << "Введите лабиринт (0 - пусто, 1 - стена, P - pdf, E - выход):\n";
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++)
            cin >> maze[i][j];        // читаем по одному символу (пробелы пропускаются)

    // Сначала помечаем все клетки как недоступные: -1 значит "сюда не попасть"
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++)
            dp[i][j] = -1;

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (maze[i][j] == '1')        // стена - сюда не пройти, оставляем -1
                continue;

            int best = -1;                // лучший результат среди соседей сверху и слева
            if (i == 0 && j == 0)         // стартовая клетка 
                best = 0;
            if (i > 0 && dp[i - 1][j] > best)   // можно прийти сверху и там лучше
                best = dp[i - 1][j];
            if (j > 0 && dp[i][j - 1] > best)   // можно прийти слева и там лучше
                best = dp[i][j - 1];

            if (best == -1)               // ни сверху, ни слева не дойти - клетка недоступна
                continue;

            if (maze[i][j] == 'P')        // в клетке pdf - забираем его
                best++;
            dp[i][j] = best;              // запоминаем результат для клетки
        }
    }

    // Ищем выход E и смотрим, сколько pdf можно было собрать до него
    int answer = -1;
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++)
            if (maze[i][j] == 'E')
                answer = dp[i][j];

    if (answer == -1)
        cout << "До выхода дойти невозможно\n";
    else
        cout << "Максимум pdf-файлов: " << answer << "\n";
    return 0;
}
